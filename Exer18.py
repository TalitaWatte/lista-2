#Algoritmo: Abrir uma porta trancada
# Aproximar-se da porta.
# Verificar se a porta está trancada.
# Se estiver trancada, localizar a chave correta.
# Segurar a chave.
# Inserir a chave na fechadura.
# Girar a chave no sentido correto até destrancar a porta.
# Retirar a chave da fechadura.
# Segurar a maçaneta.
# Girar a maçaneta.
# Empurrar a porta, no sentido da abertura.
